test("displaced external version is presented and can be restored without losing local edits", () => {
  const { state, requests } = fixture("base")
  state.edit("local")
  state.flush()
  requests.shift().complete({ status: "conflict", recovery: "conflict-123-01234567.txt" })
  state.refresh()
  assert.equal(requests[0].recovery, "conflict-123-01234567.txt")
  requests.shift().complete({ status: "ok", text: "local", revision: "local-rev", recoveryText: "external", recoveryRevision: "ext-rev" })
  assert.equal(state.externalText, "external")
  state.resolve("external")
  requests.shift().complete({ status: "ok", text: "local", revision: "local-rev", recoveryText: "external", recoveryRevision: "ext-rev" })
  assert.equal(requests[0].text, "external")
  assert.equal(requests[0].revision, "local-rev")
  assert.equal(requests[0].recoveryRevision, "ext-rev")
  state.edit("new local")
  requests.shift().complete({ status: "ok", revision: "ext-rev" })
  assert.equal(state.text, "new local")
  assert.equal(state.conflict, true)
  assert.equal(state.externalText, "external")
})

test("displaced conflict keep local checks both versions before writing", () => {
  const { state, requests } = fixture("base")
  state.edit("local")
  state.flush()
  requests.shift().complete({ status: "conflict", recovery: "conflict-123-01234567.txt" })
  state.refresh()
  const external = { status: "ok", text: "local", revision: "local-rev", recoveryText: "external", recoveryRevision: "ext-rev" }
  requests.shift().complete(external)
  state.resolve("local")
  requests.shift().complete(external)
  assert.equal(requests[0].text, "local")
  assert.equal(requests[0].recoveryRevision, "ext-rev")
  requests.shift().complete({ status: "ok", revision: "local-rev" })
  assert.equal(state.conflict, false)
  assert.equal(state.dirty, false)
})

test("new disk change during displaced resolution remains a conflict and preserves recovery", () => {
  const { state, requests } = fixture("base")
  state.edit("local")
  state.flush()
  requests.shift().complete({ status: "conflict", recovery: "conflict-123-01234567.txt" })
  state.refresh()
  requests.shift().complete({ status: "ok", text: "local", revision: "one", recoveryText: "displaced", recoveryRevision: "ext" })
  state.resolve("external")
  requests.shift().complete({ status: "ok", text: "new disk", revision: "two", recoveryText: "displaced", recoveryRevision: "ext" })
  assert.equal(state.conflict, true)
  assert.equal(state.text, "local")
  assert.equal(state.externalText, "new disk")
  assert.equal(requests.length, 0)
})


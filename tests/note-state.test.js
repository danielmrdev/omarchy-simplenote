test("disk change before first recovery read is not silently overwritten", () => {
  const { state, requests } = fixture("base")
  state.edit("local")
  state.flush()
  requests.shift().complete({ status: "conflict", recovery: "conflict-123-01234567.txt", writtenRevision: "local-rev" })
  state.refresh()
  requests.shift().complete({ status: "ok", text: "new disk", revision: "new-rev", recoveryText: "displaced", recoveryRevision: "ext" })
  assert.equal(state.conflict, true)
  assert.equal(state.externalText, "new disk")
  assert.equal(state.text, "local")
  state.resolve("local")
  assert.equal(requests[0].recovery, null)
})
